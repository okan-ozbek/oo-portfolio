import { randomBytes, scrypt as scryptCallback, timingSafeEqual } from "node:crypto";
import { promisify } from "node:util";

const scrypt = promisify(scryptCallback);
const options = { N: 32768, r: 8, p: 1, maxmem: 64 * 1024 * 1024 };
const hashPattern = /^scrypt-v1:([a-f0-9]{32}):([a-f0-9]{128})$/;

export function validatePasswordHash(hash) {
  if (!hashPattern.test(hash ?? "")) throw new Error("ADMIN_PASSWORD_HASH must be a scrypt-v1 hash generated by npm run admin:password.");
  return hash;
}

export async function hashPassword(password) {
  if (typeof password !== "string" || password.length < 16 || password.length > 256) {
    throw new Error("Use a password between 16 and 256 characters.");
  }
  const salt = randomBytes(16).toString("hex");
  const key = await scrypt(password, salt, 64, options);
  return `scrypt-v1:${salt}:${key.toString("hex")}`;
}

export async function verifyPassword(password, hash) {
  if (typeof password !== "string" || password.length > 256) return false;
  const [, salt, expected] = validatePasswordHash(hash).match(hashPattern);
  const actual = await scrypt(password, salt, 64, options);
  return timingSafeEqual(actual, Buffer.from(expected, "hex"));
}
